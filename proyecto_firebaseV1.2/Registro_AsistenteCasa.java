    private Map<String, Object> crearMapeoDatosAsistCasa(AsistenteCasa asistentecasa) {
        Map<String, Object> datos = new HashMap();

        datos.put("Nombre", asistentecasa.getNombre());
        datos.put("Precio", asistentecasa.getPrecio());
        datos.put("stock", asistentecasa.getStock());
        datos.put("Marca", asistentecasa.getMarca());
        datos.put("Modelo", asistentecasa.getModelo());
        datos.put("Garantía", asistentecasa.getGarantia());
        datos.put("TipoDispositivo", asistentecasa.getTipoDispositivo());
        datos.put("protocoloComunicacion", asistentecasa.getProtocoloComunicacion());
        datos.put("CompatibilidadAsistente", asistentecasa.getCompatibilidadAsistente());
        datos.put("TienePantalla", asistentecasa.isTienePantalla());
        datos.put("EntradaSalida", asistentecasa.getEntradasSalidas());
        datos.put("esInalambrico", asistentecasa.isEsInalambrico());
        datos.put("RangoConexion", asistentecasa.getRangoConexion());
        datos.put("RequiereHub", asistentecasa.isRequiereHub());

        return datos;
    }

    private void guardar() {
        AsistenteCasa ia = crearAsistente();
        try {
            Map<String, Object> datos = crearMapeoDatosAsistCasa(ia);
            Crud_AsistenteCasa.guardarAsistenteCasa("AsistenteCasa", String.valueOf(ia.getId()), datos);
            JOptionPane.showMessageDialog(null, "Guardado de datos con exito");
            clearForm();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al guarda los datos.");
            System.err.println("Error al introducir los datos");
        }finally {
            Crud_AsistenteCasa.cargarTablaAsistenteCasa(tbTablaAsistenteCasa);

        }

    }

    private void actualizar() {
        AsistenteCasa ia = crearAsistente();
        try {
            Map<String, Object> datos = crearMapeoDatosAsistCasa(ia);
            Crud_AsistenteCasa.actualizarAsistenteCasa("AsistenteCasa", String.valueOf(ia.getId()), datos);
            JOptionPane.showMessageDialog(null, "Actualización de datos con exito");
            clearForm();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al actualizar los datos.");
            System.err.println("Error al introducir los datos");
        }finally {
            Crud_AsistenteCasa.cargarTablaAsistenteCasa(tbTablaAsistenteCasa);

        }
    }

