    private void BusquedaID() {

        try {
            String idBusqueda = txtID.getText().trim();

            if (idBusqueda.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Ingrese un ID de Busqueda en el campo 'ID'");
                return;
            }

            AsistenteCasa iaBusqueda = Crud_AsistenteCasa.buscarAsistenteCasa(idBusqueda);
            if (iaBusqueda != null) {

                llenarCamposAsistenteCasa(iaBusqueda);
                JOptionPane.showMessageDialog(null, "Ingrese un ID de Busqueda en el campo 'ID'");
                mostrarEnTabla(iaBusqueda);
            } else {
                JOptionPane.showMessageDialog(null, "Asistente no encontrado.");
                clearForm();
            }

        } catch (Exception e) {

            System.err.println("Error al buscar computadora: " + e.getMessage());

        }finally {
            Crud_AsistenteCasa.cargarTablaAsistenteCasa(tbTablaAsistenteCasa);

        }

    }

